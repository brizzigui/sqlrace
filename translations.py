from flask import session

def translate(key, **kwargs):
    lang = session.get('lang', 'en')
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS['en'])
    msg = lang_dict.get(key, TRANSLATIONS['en'].get(key, key))
    if kwargs:
        try:
            return msg.format(**kwargs)
        except Exception:
            pass
    return msg

